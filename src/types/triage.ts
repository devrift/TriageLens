/**
 * TriageLens Core Type Definitions
 * 
 * Strict contracts, enums, diagnostic payloads, telemetry interfaces,
 * session storage records, baseline comparisons, and companion AI guidance types.
 */

export type ScanMode = 'face' | 'finger';

export type TriageState =
  | 'IDLE'
  | 'STARTING'
  | 'CALIBRATING'
  | 'ACQUIRING'
  | 'ANALYZING'
  | 'COMPLETE'
  | 'FAILED';

export type FailureReason =
  | 'LOW_LIGHT'
  | 'MOTION_ARTIFACT'
  | 'FINGER_OFF'
  | 'POOR_SNR'
  | 'CAMERA_ERROR';

/**
 * Verified vital sign telemetry payload emitted upon acquisition and analysis.
 */
export interface VitalsTelemetry {
  timestamp: number;
  heartRateBpm: number;
  respirationRateRpm: number;
  strokeAsymmetryDelta: number;
  sqiScore: number;
  rawWaveformSample: number;
  filteredWaveformSample: number;
  snrDb?: number;
}

/**
 * Real-time per-frame signal and hardware quality diagnostic.
 */
export interface QualityDiagnostic {
  isAcceptable: boolean;
  reason?: FailureReason;
  luma: number;
  motionArtifactDetected?: boolean;
  insufficientLuminance?: boolean;
  fingerContactLost?: boolean;
  spectralNoiseHigh?: boolean;
}

/**
 * Scan coordinator configuration options.
 */
export interface CoordinatorConfig {
  scanDurationMs: number;
  calibrationDurationMs: number;
  sampleRateHz: number;
  sqiThreshold: number;
  asymmetryAlertThreshold: number;
  minLumaThreshold: number;
}

/**
 * Strongly typed camera hardware errors.
 */
export type CameraErrorCode =
  | 'CAMERA_PERMISSION_DENIED'
  | 'CAMERA_NOT_FOUND'
  | 'TORCH_NOT_SUPPORTED'
  | 'CAMERA_ERROR';

export class CameraStreamError extends Error {
  public readonly code: CameraErrorCode;

  constructor(code: CameraErrorCode, message?: string) {
    super(message ?? code);
    this.name = 'CameraStreamError';
    this.code = code;
    Object.setPrototypeOf(this, CameraStreamError.prototype);
  }
}

/**
 * Results returned from per-frame facial tracking.
 */
export interface FaceTrackingResult {
  foreheadRgb: [number, number, number];
  luma: number;
  asymmetryDelta: number;
  isTrackingValid: boolean;
  motionDetected: boolean;
}

/**
 * Results returned from per-frame rear-camera finger sampling.
 */
export interface FingerSampleResult {
  isFingerPlaced: boolean;
  signalValue: number;
  rgb: [number, number, number];
  luma: number;
  timestamp: number;
  isPlacementValid?: boolean;
}

export interface NormalizedLandmark {
  x: number;
  y: number;
  z: number;
}

/**
 * Persistent telemetry record stored in local database/storage.
 */
export interface TriageSessionRecord {
  id: string;
  timestamp: number;
  mode: ScanMode;
  telemetry: VitalsTelemetry;
  durationMs: number;
  qualitySummary: {
    averageSqi: number;
    averageLuma: number;
    acceptableRate: number;
  };
  notes?: string;
}

/**
 * Delta comparison between an active scan and a previous baseline session.
 */
export interface VitalsBaselineDelta {
  deltaHeartRateBpm: number;
  deltaRespirationRateRpm: number;
  deltaStrokeAsymmetry: number;
  timeSinceBaselineMs: number;
  hasElevatedHeartRate: boolean;
  hasElevatedRespiration: boolean;
  hasAsymmetryAlert: boolean;
}

/**
 * Input configuration passed to the AI Triage Companion service.
 */
export interface TriageCompanionInput {
  telemetry: VitalsTelemetry;
  mode: ScanMode;
  language?: string;
  tone?: 'calm' | 'clinical' | 'emergency';
  baselineDelta?: VitalsBaselineDelta;
  patientContext?: string;
}

/**
 * Guidance and speech payload generated by the AI Triage Companion.
 */
export interface TriageCompanionOutput {
  summaryText: string;
  guidanceText: string;
  severityLevel: 'NORMAL' | 'ELEVATED' | 'CRITICAL' | 'INVALID';
  actionableAdvice: string[];
  audioBase64?: string;
  audioMimeType?: string;
  isOfflineFallback: boolean;
  generatedAt: number;
}
